void Require(bool value, const char* reason) { if (!value) throw std::runtime_error(reason); }
void Write(const fs::path& path, std::string_view text) {
    fs::create_directories(path.parent_path()); std::ofstream out(path, std::ios::binary);
    out.write(text.data(), text.size()); Require(bool(out), "fixture write failed");
}
std::string Read(const fs::path& path) {
    std::ifstream in(path, std::ios::binary); return {std::istreambuf_iterator<char>(in), {}};
}
struct Events : EventSink {
    std::vector<OperationEvent> seen;
    void Emit(OperationEvent event) noexcept override { seen.push_back(std::move(event)); }
};
// Independent ZIP32 reader checks entry bytes, not just existence/success.
std::map<std::string, std::string> Entries(const fs::path& archive) {
    const auto data = Read(archive); std::map<std::string, std::string> entries;
    const auto u16 = [&](std::size_t p) { Require(p + 2 <= data.size(), "ZIP truncated");
        std::uint16_t v; std::memcpy(&v, data.data() + p, 2); return v; };
    const auto u32 = [&](std::size_t p) { Require(p + 4 <= data.size(), "ZIP truncated");
        std::uint32_t v; std::memcpy(&v, data.data() + p, 4); return v; };
    std::size_t p = 0;
    while (u32(p) == 0x04034b50) {
        Require(u16(p + 8) == 0 && u16(p + 6) == 0x0800, "unexpected compression/flags");
        const auto size = u32(p + 18); Require(size == u32(p + 22), "ZIP size differs");
        const auto name = u16(p + 26), extra = u16(p + 28);
        Require(p + 30 + name + extra + size <= data.size(), "ZIP entry truncated");
        const auto key = data.substr(p + 30, name);
        Require(entries.emplace(key, data.substr(p + 30 + name + extra, size)).second, "duplicate ZIP entry");
        p += 30 + name + extra + size;
    }
    Require(u32(p) == 0x02014b50 && data.size() >= 22 &&
        u32(data.size() - 22) == 0x06054b50, "ZIP directory/footer missing");
    Require(u16(data.size() - 12) == entries.size(), "ZIP directory count differs");
    return entries;
}
int main(int argc, char** argv) {
    fs::path root;
    try {
        Require(argc == 3, "expected metadata fixture and CLI");
        root = fs::temp_directory_path() / ("OPENFRUIT-unsigned-package-" + NewOperationId());
        fs::create_directories(root);
        auto project = UniversalProject::Inspect(fs::absolute(argv[1]).wstring(), "Debug");
        Require(project.is_valid, "fixture discovery failed");
        auto spec = UniversalProject::ToPackagingSpec(project);
        AppBuildResult built; built.success = true; built.build_root = (root / "build").wstring();
        built.product_path = (root / "compiler-product" / (spec.app_name + L".app")).wstring();
        built.executable_path = (fs::path(built.product_path) / spec.app_name).wstring();
        // This stage input sentinel tests packaging only, not compilation or
        // Mach-O validity. Identity/resources still come from project metadata.
        Write(built.executable_path, "owned linked-stage bytes");
        Write(fs::path(built.product_path) / "Generated" / "compiler-resource", "owned generated bytes");
        Write(fs::path(built.build_root) / "Payload" / "unrelated-stale", "preserve old payload");
        Write(fs::path(built.build_root) / (spec.app_name + L"-signed.ipa"), "preserve signed artifact");
        // Unreadable/nonexistent signing references must not enter unsigned flow.
        spec.p12_path = (root / "no-credential.p12").wstring();
        spec.provisioning_profile_path = (root / "no-profile.mobileprovision").wstring();
        spec.dpapi_password_path = (root / "no-password.dpapi").wstring();
        auto sink = std::make_shared<Events>(); auto context = std::make_shared<OperationContext>(); context->sink = sink;
        PackagingResult packaged;
        { OperationBinding binding(context); packaged = PackagerSigner::PackageUnsigned(root.wstring(), built, spec); }
        Require(packaged.success && !packaged.unsigned_ipa_path.empty() && packaged.signed_ipa_path.empty()
            && packaged.prepared_entitlement_requests.empty(), "unsigned mode entered signing or failed");
        for (const auto& event : sink->seen)
            Require(event.kind != "process.started", "simple packaging launched a signer/provider process");
        const auto entries = Entries(packaged.unsigned_ipa_path);
        const auto prefix = "Payload/" + Win32Process::ToNarrow(spec.app_name) + ".app/";
        Require(entries.at(prefix + Win32Process::ToNarrow(spec.app_name)) == "owned linked-stage bytes", "executable lost");
        Require(entries.at(prefix + "Generated/compiler-resource") == "owned generated bytes", "generated resource lost");
        Require(entries.at(prefix + "Info.plist").find(Win32Process::ToNarrow(spec.bundle_id)) != std::string::npos, "derived identity lost");
        Require(!entries.contains("Payload/unrelated-stale"), "stale sibling packaged");
        Require(Read(built.executable_path) == "owned linked-stage bytes" &&
            Read(fs::path(built.product_path) / "Generated/compiler-resource") == "owned generated bytes", "producer inputs changed");
        Require(Read(fs::path(built.build_root) / (spec.app_name + L"-signed.ipa")) == "preserve signed artifact", "existing signed artifact removed");
        const auto previous = Read(packaged.unsigned_ipa_path);
        HANDLE lock = CreateFileW(fs::path(packaged.unsigned_ipa_path).c_str(), GENERIC_READ,
            FILE_SHARE_READ, nullptr, OPEN_EXISTING, 0, nullptr);
        Require(lock != INVALID_HANDLE_VALUE, "cannot lock previous IPA");
        const auto denied = PackagerSigner::PackageUnsigned(root.wstring(), built, spec);
        CloseHandle(lock);
        Require(!denied.success && Read(packaged.unsigned_ipa_path) == previous, "failed publication damaged previous IPA");
        built.success = false;
        Require(!PackagerSigner::PackageUnsigned(root.wstring(), built, spec).success
            && Read(packaged.unsigned_ipa_path) == previous, "failed compiler accepted or previous IPA damaged");
        for (const auto* option : {L"--deploy", L"--p12", L"--provision"}) {
            std::vector<std::wstring> args{fs::absolute(argv[2]).wstring(), L"package", L"absent-project", option};
            if (std::wstring(option) != L"--deploy") args.push_back(L"absent-signing-file");
            const auto reply = Win32Process::Run(args.front(), args, L"", {{L"OPENFRUIT_USER_STATE", (root / "user").wstring()}});
            Require(reply.exit_code == 2 && reply.std_err.find("unsigned IPA") != std::string::npos,
                "CLI accepted conflicting signed/deploy intent");
        }
        Require(!fs::exists(root / "user" / "credentials" / "secrets.json"), "package initialized signing credentials");
        // --- Candidate B Tests ---
        // 1. In-process Mach-O inspection
        const fs::path mach_dir = root / "macho_test";
        fs::create_directories(mach_dir);

        // 1a. Thin 64-bit ARM64 MH_DYLIB (filetype = 0x6)
        {
            const fs::path dylib_path = mach_dir / "libtest.dylib";
            std::vector<uint8_t> bytes(32, 0);
            // magic 0xfeedfacf (LE)
            bytes[0] = 0xcf; bytes[1] = 0xfa; bytes[2] = 0xed; bytes[3] = 0xfe;
            // cputype CPU_TYPE_ARM64 = 0x0100000c (LE)
            bytes[4] = 0x0c; bytes[5] = 0x00; bytes[6] = 0x00; bytes[7] = 0x01;
            // cpusubtype 0
            bytes[8] = 0x00; bytes[9] = 0x00; bytes[10] = 0x00; bytes[11] = 0x00;
            // filetype MH_DYLIB = 0x6 (LE)
            bytes[12] = 0x06; bytes[13] = 0x00; bytes[14] = 0x00; bytes[15] = 0x00;
            
            std::ofstream out(dylib_path, std::ios::binary);
            out.write(reinterpret_cast<const char*>(bytes.data()), bytes.size());
            out.close();

            Require(PackagerSigner::IsDynamicMachOBinary(dylib_path), "Thin MH_DYLIB should be detected as dynamic");

            // Wrap in framework
            const fs::path fwk_dir = mach_dir / "DynTest.framework";
            fs::create_directories(fwk_dir);
            fs::copy_file(dylib_path, fwk_dir / "DynTest");
            Require(PackagerSigner::IsDynamicFramework(root, fwk_dir), "DynTest.framework should be detected as dynamic");
        }

        // 1b. Thin MH_EXECUTE (filetype = 0x2)
        {
            const fs::path exec_path = mach_dir / "test_exec";
            std::vector<uint8_t> bytes(32, 0);
            bytes[0] = 0xcf; bytes[1] = 0xfa; bytes[2] = 0xed; bytes[3] = 0xfe;
            bytes[12] = 0x02; bytes[13] = 0x00; bytes[14] = 0x00; bytes[15] = 0x00; // MH_EXECUTE
            std::ofstream out(exec_path, std::ios::binary);
            out.write(reinterpret_cast<const char*>(bytes.data()), bytes.size());
            out.close();

            Require(!PackagerSigner::IsDynamicMachOBinary(exec_path), "Thin MH_EXECUTE should not be dynamic library");
        }

        // 1c. Universal Fat Mach-O with MH_DYLIB slice at offset 0x100
        {
            const fs::path fat_path = mach_dir / "fat_dylib";
            std::vector<uint8_t> bytes(0x200, 0);
            // FAT_MAGIC = 0xcafebabe (Big Endian)
            bytes[0] = 0xca; bytes[1] = 0xfe; bytes[2] = 0xba; bytes[3] = 0xbe;
            // nfat_arch = 1 (BE)
            bytes[4] = 0x00; bytes[5] = 0x00; bytes[6] = 0x00; bytes[7] = 0x01;
            // fat_arch 0: cputype(4), cpusubtype(4), offset=0x100(4), size=0x100(4), align(4)
            // offset at bytes[16..19] (BE) -> 0x00000100
            bytes[16] = 0x00; bytes[17] = 0x00; bytes[18] = 0x01; bytes[19] = 0x00;

            // Mach-O header at offset 0x100
            bytes[0x100] = 0xcf; bytes[0x101] = 0xfa; bytes[0x102] = 0xed; bytes[0x103] = 0xfe;
            bytes[0x10c] = 0x06; bytes[0x10d] = 0x00; bytes[0x10e] = 0x00; bytes[0x10f] = 0x00; // MH_DYLIB

            std::ofstream out(fat_path, std::ios::binary);
            out.write(reinterpret_cast<const char*>(bytes.data()), bytes.size());
            out.close();

            Require(PackagerSigner::IsDynamicMachOBinary(fat_path), "Fat binary with MH_DYLIB slice should be detected as dynamic");
        }

        // 1d. Static archive !<arch>\n
        {
            const fs::path static_path = mach_dir / "libstatic.a";
            std::ofstream out(static_path, std::ios::binary);
            out << "!<arch>\n/               0           0     0     0       0        `\n";
            out.close();
            Require(!PackagerSigner::IsDynamicMachOBinary(static_path), "Static archive must not be dynamic");
        }

        // 2. EXECUTABLE_NAME preservation in GenerateInfoPlist
        {
            PackagingSpec exec_spec;
            exec_spec.app_name = L"BaseApp";
            exec_spec.product_name = L"BaseApp";
            exec_spec.executable_name = L"CustomExecutable";
            const fs::path custom_plist = mach_dir / "CustomInfo.plist";
            Require(PackagerSigner::GenerateInfoPlist(custom_plist.wstring(), exec_spec), "GenerateInfoPlist failed");
            const std::string content = Read(custom_plist);
            Require(content.find("<key>CFBundleExecutable</key>\n    <string>CustomExecutable</string>") != std::string::npos,
                "CFBundleExecutable did not use executable_name");
        }

        fs::remove_all(root); // Newly reserved owned fixture only.
        std::cout << "PASS: unsigned service preserves producer bytes/identity, publishes complete IPA without signing, preserves previous artifacts on failure\n";
        return 0;
    } catch (const std::exception& error) { std::cerr << "FAIL: " << error.what() << "\nEvidence: " << root.string() << '\n'; return 1; }
}
