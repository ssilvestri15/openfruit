PackageBuildResult
PackageEngine::BuildXcodePackages(
    const std::wstring& repo_root,
    const std::wstring& project_path,
    const SDKInfo& sdk_info,
    const std::wstring& configuration,
    unsigned int jobs,
    const GitSourceView* independent_sources,
    const std::string& selected_target_id,
    const XcodeDependencyOptions* dependency_options
) {
    const fs::path root(
        repo_root
    );

    const auto project =
        XcodeProject::Load(
            fs::path(project_path)
        );

    if (!project) {
        std::cerr
            << "OPENFRUIT PackageEngine v4: unable to parse Xcode project."
            << std::endl;

        return {};
    }

    // The application service freezes the project/UUID before preparing its
    // source view. Never replace that selected root with another application.
    std::optional<XcodeTarget> target;
    if (selected_target_id.empty()) {
        target = project->MainApplicationTarget();
    } else {
        for (const auto& candidate : project->Targets())
            if (candidate.id == selected_target_id) { target = candidate; break; }
    }

    if (!target) {
        std::cerr
            << "OPENFRUIT PackageEngine v4: selected Xcode target is missing."
            << std::endl;

        return {};
    }

    std::string selected_configuration = Win32Process::ToNarrow(configuration);
    if (dependency_options && dependency_options->strict_build_settings) {
        std::string error;
        const auto canonical = project->ResolveConfigurationName(*target, selected_configuration, &error);
        if (!canonical) {
            std::cerr << "OPENFRUIT PackageEngine v4: " << error << std::endl;
            return {};
        }
        selected_configuration = *canonical;
    }

    auto resolved =
        project->ResolveTarget(
            *target,
            selected_configuration,
            dependency_options ? *dependency_options : XcodeDependencyOptions{}
        );

    if (!resolved) {
        std::cerr
            << "OPENFRUIT PackageEngine v4: unable to resolve selected Xcode target."
            << std::endl;
        return {};
    }

    if (const auto operation = CurrentOperationContext()) {
        auto metadata = JsonValue::ObjectValue();
        metadata.Set("project", JsonValue::String(project->ProjectBundle().string()));
        metadata.Set("target_id", JsonValue::String(target->id));
        metadata.Set("configuration", JsonValue::String(selected_configuration));
        operation->Emit("xcode.packages.selected", std::move(metadata));
    }

    const CarthageResolveResult carthage =
        ResolveCarthageBinaryFrameworks(
            project->SourceRoot(),
            resolved->frameworks
        );
    if (!carthage.success) {
        std::cerr << "OPENFRUIT Carthage: " << carthage.error << std::endl;
        return {};
    }
    resolved->frameworks.insert(
        resolved->frameworks.end(),
        carthage.device_frameworks.begin(),
        carthage.device_frameworks.end()
    );

    if (resolved->package_products.empty()) {

        std::cout
            << "OPENFRUIT PackageEngine v4: selected target has no "
               "SwiftPM product dependencies."
            << std::endl;

        PackageBuildResult empty;
        empty.success = true;
        for (const auto& framework : carthage.device_frameworks) {
            empty.frameworks.push_back(framework.wstring());
            empty.linked_frameworks.push_back(framework.wstring());
        }
        return empty;
    }

    const fs::path synthetic =
        root /
        "build" /
        "xcode-packages-v4" /
        project->Name();

    if (!GenerateSyntheticPackage(
            *project,
            *resolved,
            synthetic,
            sdk_info)) {

        std::cerr
            << "OPENFRUIT PackageEngine v4: unable to generate native "
               "synthetic package manifest."
            << std::endl;

        return {};
    }

    /*
     * Only the exact previous cache for this same synthetic project may be
     * reused. This keeps an expensive validated cache warm while v4
     * migrates to content-addressed fingerprints.
     */
    const fs::path legacy_synthetic =
        root /
        "build" /
        "xcode-packages" /
        project->Name();

    const std::string legacy_key =
        LegacyPathKey(
            legacy_synthetic
        );

    PackageBuildResult result = BuildNativePackage(
        root,
        synthetic,
        sdk_info,
        Win32Process::ToWide(selected_configuration),
        jobs,
        legacy_key,
        &*project,
        &*resolved,
        independent_sources
    );
    if (!result.success) return result;

    for (const auto& framework : carthage.device_frameworks) {
        result.frameworks.push_back(framework.wstring());
        result.linked_frameworks.push_back(framework.wstring());
    }
    return result;
}

PackageBuildResult
PackageEngine::BuildSwiftPMPackage(
    const std::wstring& repo_root,
    const std::wstring& package_path,
    const SDKInfo& sdk_info,
    const std::wstring& configuration,
    unsigned int jobs
) {
    const fs::path root(
        repo_root
    );

    const fs::path package =
        fs::absolute(
            fs::path(package_path)
        ).lexically_normal();

    return BuildNativePackage(
        root,
        package,
        sdk_info,
        configuration,
        jobs,
        std::nullopt
    );
}

