std::wstring ReadEnvironmentVariable(
    const wchar_t* name
) {
    const DWORD required =
        GetEnvironmentVariableW(
            name,
            nullptr,
            0
        );

    if (required == 0) {
        return {};
    }

    std::wstring value(
        required,
        L'\0'
    );

    const DWORD written =
        GetEnvironmentVariableW(
            name,
            value.data(),
            required
        );

    if (written == 0 ||
        written >= required) {
        return {};
    }

    value.resize(written);
    return value;
}

bool WriteText(
    const fs::path& path,
    const std::string& value
) {
    std::error_code ec;
    fs::create_directories(
        path.parent_path(),
        ec
    );

    if (ec) {
        return false;
    }

    std::ofstream output(
        path,
        std::ios::binary |
        std::ios::trunc
    );

    if (!output) {
        return false;
    }

    output.write(
        value.data(),
        static_cast<std::streamsize>(
            value.size()
        )
    );

    return output.good();
}

// Only OPENFRUIT-generated metadata uses this helper. Preserve timestamps when
// the generated bytes are unchanged so SwiftPM can keep its incremental plan.
bool WriteGeneratedTextIfChanged(const fs::path& path, const std::string& value) {
    if (fs::is_regular_file(path) && ReadFileText(path) == value) return true;
    fs::create_directories(path.parent_path());
    return AtomicFile::Publish(path, value);
}

bool CopyGeneratedFileIfChanged(const fs::path& source, const fs::path& destination) {
    const auto expected = Sha256File(source);
    if (!expected) return false;
    const auto attributes = GetFileAttributesW(destination.c_str());
    if (attributes != INVALID_FILE_ATTRIBUTES &&
        (attributes & (FILE_ATTRIBUTE_REPARSE_POINT | FILE_ATTRIBUTE_DIRECTORY))) return false;
    if (attributes != INVALID_FILE_ATTRIBUTES) {
        const auto actual = Sha256File(destination);
        if (!actual) return false;
        if (*actual == *expected) return true;
    }
    std::error_code ec;
    fs::copy_file(source, destination, fs::copy_options::overwrite_existing, ec);
    if (ec) return false;
    return Sha256File(destination) == expected;
}

bool DigestText(const std::string& text) {
    return text.size() == 64 && text.find_first_not_of("0123456789abcdef") == std::string::npos;
}

std::optional<std::string> ProxyFileDigest(const fs::path& path) {
    HANDLE handle = CreateFileW(path.c_str(), GENERIC_READ, FILE_SHARE_READ,
        nullptr, OPEN_EXISTING, FILE_FLAG_OPEN_REPARSE_POINT, nullptr);
    if (handle == INVALID_HANDLE_VALUE) return {};
    BY_HANDLE_FILE_INFORMATION info{};
    const bool ordinary = GetFileInformationByHandle(handle, &info) &&
        !(info.dwFileAttributes & (FILE_ATTRIBUTE_DIRECTORY | FILE_ATTRIBUTE_REPARSE_POINT)) &&
        info.nNumberOfLinks == 1;
    auto deadline = std::chrono::steady_clock::time_point::max();
    if (const auto operation = CurrentOperationContext(); operation && operation->control)
        deadline = operation->control->deadline;
    const auto digest = ordinary ? Sha256FileHandle(handle, {}, deadline) : std::optional<std::string>{};
    CloseHandle(handle);
    return digest;
}

// Match the selected path to an exact object already pinned by provider
// admission, then hash that reader handle. No second admission or payload lease
// is introduced, and a changed ancestor cannot redirect identity collection.
std::optional<std::string> AdmittedProviderDigest(const fs::path& path,
    const DarwinMacroProvider& provider, std::chrono::steady_clock::time_point deadline) {
    const HANDLE selected = CreateFileW(path.c_str(), GENERIC_READ, FILE_SHARE_READ,
        nullptr, OPEN_EXISTING, FILE_ATTRIBUTE_NORMAL, nullptr);
    if (selected == INVALID_HANDLE_VALUE) return {};
    BY_HANDLE_FILE_INFORMATION selection{};
    const bool selected_ok = GetFileInformationByHandle(selected, &selection) &&
        !(selection.dwFileAttributes & FILE_ATTRIBUTE_DIRECTORY);
    std::optional<std::string> digest;
    if (selected_ok) for (const auto& retained : provider.retained_inputs) {
        BY_HANDLE_FILE_INFORMATION admitted{};
        if (retained && GetFileInformationByHandle(retained.get(), &admitted) &&
            admitted.dwVolumeSerialNumber == selection.dwVolumeSerialNumber &&
            admitted.nFileIndexHigh == selection.nFileIndexHigh &&
            admitted.nFileIndexLow == selection.nFileIndexLow) {
            digest = Sha256FileHandleStatCached(retained.get(), ToolPaths::FileDigestCache(), {}, deadline);
            break;
        }
    }
    CloseHandle(selected);
    return digest;
}

bool PrepareProxyToolchain(const fs::path& source, const fs::path& directory,
    const fs::path& receipt, const std::string& semantic, std::string& error, bool* reused) {
    error.clear();
    if (reused) *reused = false;
    try {
        const auto fail = [&](const char* message) { error = message; return false; };
        if (!source.is_absolute() || !directory.is_absolute() || !receipt.is_absolute() || !DigestText(semantic))
            return fail("Compiler proxy preparation requires absolute owned paths and a complete identity.");
        const auto container = directory.parent_path().parent_path();
        if (directory.parent_path().filename() != L"s" || directory.filename() != L"OPENFRUIT-ios-target-toolchain" ||
            receipt != container / "i" / "compiler-proxy.json")
            return fail("Compiler proxy receipt is outside its execution-container ownership scope.");
        for (const auto& path : {container, directory.parent_path(), directory, receipt.parent_path()}) {
            const auto attributes = GetFileAttributesW(path.c_str());
            if (attributes != INVALID_FILE_ATTRIBUTES &&
                (!(attributes & FILE_ATTRIBUTE_DIRECTORY) || (attributes & FILE_ATTRIBUTE_REPARSE_POINT)))
                return fail("Compiler proxy ownership refuses directory aliases.");
        }
        const auto source_hash = ProxyFileDigest(source);
        if (!source_hash) return fail("Current compiler proxy executable cannot be verified.");
        std::map<std::string, std::pair<fs::path, std::string>> inputs;
        for (const char* name : {"clang.exe", "clang++.exe", "swiftc.exe"})
            inputs.emplace(name, std::make_pair(source, *source_hash));
        for (const auto& entry : fs::directory_iterator(source.parent_path())) {
            if (ToLowerAscii(entry.path().extension().string()) != ".dll") continue;
            const auto digest = ProxyFileDigest(entry.path());
            if (!digest) return fail("Adjacent compiler proxy runtime cannot be verified.");
            inputs.emplace(entry.path().filename().string(), std::make_pair(entry.path(), *digest));
        }
        std::optional<JsonValue> previous;
        if (fs::exists(receipt)) {
            if (fs::file_size(receipt) > 1024 * 1024) return fail("Compiler proxy receipt exceeds its metadata bound.");
            if (!ProxyFileDigest(receipt)) return fail("Compiler proxy ownership receipt is not an ordinary independent file.");
            previous = JsonValue::Parse(ReadFileText(receipt));
            if (!previous || previous->GetString("schema") != "openfruit.compiler-proxy.v1" ||
                previous->GetString("directory") != directory.generic_string() ||
                (previous->GetString("phase") != "prepared" && previous->GetString("phase") != "complete"))
                return fail("Compiler proxy ownership receipt is corrupt or incompatible.");
        } else if (fs::exists(directory) && !fs::is_empty(directory)) {
            return fail("Legacy compiler proxy files have no ownership receipt and are preserved.");
        }
        std::map<std::string, std::string> recorded;
        if (previous) {
            const auto* files = previous->Get("files");
            if (!files || !files->IsObject()) return fail("Compiler proxy receipt has no owned file inventory.");
            for (const auto& [name, value] : files->ObjectItems()) {
                if (fs::path(name).filename().string() != name || !inputs.contains(name) ||
                    !value.IsString() || !DigestText(value.StringValue()))
                    return fail("Compiler proxy receipt contains unknown owned files.");
                recorded.emplace(name, value.StringValue());
            }
            if (recorded.size() != inputs.size()) return fail("Compiler proxy receipt file set differs from current inputs.");
        }
        fs::create_directories(directory);
        for (const auto& entry : fs::directory_iterator(directory)) {
            if (!recorded.contains(entry.path().filename().string()))
                return fail("Unowned compiler proxy output is preserved.");
            if (!ProxyFileDigest(entry.path())) return fail("Compiler proxy output is aliased or unreadable.");
        }
        bool compatible = previous && previous->GetString("phase") == "complete" &&
            previous->GetString("semantic_identity") == semantic;
        if (compatible) {
            for (const auto& [name, input] : inputs) {
                const auto actual = ProxyFileDigest(directory / name);
                if (!actual || *actual != recorded.at(name) ||
                    (ToLowerAscii(fs::path(name).extension().string()) == ".dll" && *actual != input.second)) {
                    compatible = false; break;
                }
            }
        }
        if (compatible) { if (reused) *reused = true; return true; }
        auto ownership = JsonValue::ObjectValue();
        ownership.Set("schema", JsonValue::String("openfruit.compiler-proxy.v1"));
        ownership.Set("phase", JsonValue::String("prepared"));
        ownership.Set("directory", JsonValue::String(directory.generic_string()));
        ownership.Set("semantic_identity", JsonValue::String(semantic));
        auto files = JsonValue::ObjectValue();
        for (const auto& [name, input] : inputs) files.Set(name, JsonValue::String(input.second));
        ownership.Set("files", std::move(files));
        if (!AtomicFile::Publish(receipt, ownership.Serialize(true)))
            return fail("Compiler proxy ownership could not be prepared.");
        for (const auto& [name, input] : inputs)
            if (!CopyGeneratedFileIfChanged(input.first, directory / name))
                return fail("Compiler proxy file could not be published; prepared ownership is retained.");
        ownership.Set("phase", JsonValue::String("complete"));
        if (!AtomicFile::Publish(receipt, ownership.Serialize(true)))
            return fail("Compiler proxy completion could not be published; prepared ownership is retained.");
        return true;
    } catch (const std::exception& failure) { error = failure.what(); return false; }
}

std::string Sha256Hex(
    const void* data,
    std::size_t size
) {
    BCRYPT_ALG_HANDLE algorithm = nullptr;

    if (!BCRYPT_SUCCESS(
            BCryptOpenAlgorithmProvider(
                &algorithm,
                BCRYPT_SHA256_ALGORITHM,
                nullptr,
                0))) {
        return {};
    }

    DWORD object_size = 0;
    DWORD actual = 0;

    if (!BCRYPT_SUCCESS(
            BCryptGetProperty(
                algorithm,
                BCRYPT_OBJECT_LENGTH,
                reinterpret_cast<PUCHAR>(
                    &object_size
                ),
                sizeof(object_size),
                &actual,
                0))) {

        BCryptCloseAlgorithmProvider(
            algorithm,
            0
        );

        return {};
    }

    std::vector<unsigned char>
        object(object_size);

    BCRYPT_HASH_HANDLE hash = nullptr;

    if (!BCRYPT_SUCCESS(
            BCryptCreateHash(
                algorithm,
                &hash,
                object.data(),
                static_cast<ULONG>(
                    object.size()
                ),
                nullptr,
                0,
                0))) {

        BCryptCloseAlgorithmProvider(
            algorithm,
            0
        );

        return {};
    }

    if (size > 0) {
        BCryptHashData(
            hash,
            reinterpret_cast<PUCHAR>(
                const_cast<void*>(data)
            ),
            static_cast<ULONG>(size),
            0
        );
    }

    unsigned char digest[32] = {};

    const bool finish_ok =
        BCRYPT_SUCCESS(
            BCryptFinishHash(
                hash,
                digest,
                sizeof(digest),
                0
            )
        );

    BCryptDestroyHash(hash);
    BCryptCloseAlgorithmProvider(
        algorithm,
        0
    );

    if (!finish_ok) {
        return {};
    }

    std::ostringstream stream;

    for (const unsigned char byte :
         digest) {
        stream
            << std::hex
            << std::setw(2)
            << std::setfill('0')
            << static_cast<unsigned int>(
                   byte
               );
    }

    return stream.str();
}

std::string LegacyPathKey(
    const fs::path& path
) {
    std::error_code ec;
    fs::path absolute =
        fs::absolute(path, ec)
            .lexically_normal();

    if (ec) {
        absolute =
            path.lexically_normal();
    }

    const std::string lower =
        ToLowerAscii(
            absolute.string()
        );

    const std::string full =
        Sha256Hex(
            lower.data(),
            lower.size()
        );

    return full.size() >= 16
        ? full.substr(0, 16)
        : full;
}

